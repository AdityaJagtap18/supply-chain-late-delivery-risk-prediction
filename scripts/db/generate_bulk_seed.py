"""
Generates scripts/db/005_seed_bulk_real_orders.sql -- a larger, more realistic demo dataset.

Why this exists: the Phase 3/4 seed data (002/003) is only 5 hand-written orders, created just
to exercise the API/UI during development. That's honest but makes the live dashboard look like
almost nothing is happening. This script samples real historical rows from the same
`final_sample.csv` ML-001's training pipeline uses (never fabricated values), and emits plain
INSERT statements for `customer`/`customer_location`/`order`/`shipment` -- the same tables and
column shapes `002_seed_phase3.sql`/`003_seed_phase4_real_categories.sql` already use.

Deliberately does NOT insert any `risk_assessment` row itself -- those must come from a real
`POST /system/batch-scoring` run against the real ML service after this seed is loaded, so every
score shown in the UI is still a real inference call, never a value written directly into the
database by this script.

Usage:
    pip install pandas
    python scripts/db/generate_bulk_seed.py > scripts/db/005_seed_bulk_real_orders.sql
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_CSV = REPO_ROOT / "final_sample.csv"

SAMPLE_SIZE = 300
RANDOM_SEED = 42

# Customer ids already used by 002_seed_phase3.sql -- never resample these.
EXISTING_CUSTOMER_IDS = {1001, 1002, 1003}

# Keep to the 4 order_status values this app's documented model (DB-ARCH-001 S2.3, OrderController's
# ALLOWED_STATUSES) actually models -- the source dataset has 9, several (SUSPECTED_FRAUD,
# CANCELED, ON_HOLD, PAYMENT_REVIEW, PENDING) this app has never been designed to filter/display.
KEPT_STATUSES = {"COMPLETE", "PENDING_PAYMENT", "PROCESSING", "CLOSED"}

REQUIRED_COLUMNS = [
    "Type",
    "Customer City",
    "Customer Id",
    "Customer Segment",
    "Customer State",
    "Customer Zipcode",
    "Customer Country",
    "Order City",
    "Order Country",
    "Order Region",
    "Order State",
    "Market",
    "Order Status",
    "Shipping Mode",
]


def sql_quote(value: object) -> str:
    """Single-quoted SQL string literal, doubling embedded quotes."""
    return "'" + str(value).replace("'", "''") + "'"


def main() -> None:
    if not SOURCE_CSV.is_file():
        print(f"Source dataset not found at {SOURCE_CSV}", file=sys.stderr)
        sys.exit(1)

    df = pd.read_csv(SOURCE_CSV)
    df = df.dropna(subset=REQUIRED_COLUMNS)
    df = df[df["Order Status"].isin(KEPT_STATUSES)]
    df = df[~df["Customer Id"].isin(EXISTING_CUSTOMER_IDS)]

    sample = df.sample(n=SAMPLE_SIZE, random_state=RANDOM_SEED).reset_index(drop=True)

    rng = random.Random(RANDOM_SEED)

    lines: list[str] = []
    lines.append("-- 005_seed_bulk_real_orders.sql")
    lines.append("--")
    lines.append(
        f"-- Generated by scripts/db/generate_bulk_seed.py ({SAMPLE_SIZE} rows, seed "
        f"{RANDOM_SEED}) from real rows in final_sample.csv -- the same file ML-001's training "
        "pipeline reads. Every customer/location/order/shipment value below is copied verbatim "
        "from a real historical row, never invented. No risk_assessment row is inserted here --"
    )
    lines.append(
        "-- run a real POST /system/batch-scoring afterward so every score shown in the UI is a"
    )
    lines.append("-- real inference call, not a value this script wrote directly.")
    lines.append("")
    lines.append("BEGIN;")
    lines.append("")

    seen_customers: dict[int, dict] = {}
    for _, row in sample.iterrows():
        customer_id = int(row["Customer Id"])
        if customer_id not in seen_customers:
            seen_customers[customer_id] = row

    lines.append("INSERT INTO customer (customer_id, customer_segment) VALUES")
    customer_values = [
        f"    ({customer_id}, {sql_quote(row['Customer Segment'])})"
        for customer_id, row in seen_customers.items()
    ]
    lines.append(",\n".join(customer_values) + ";")
    lines.append("")

    lines.append(
        "INSERT INTO customer_location (customer_id, customer_city, customer_state, "
        "customer_zipcode, customer_country) VALUES"
    )
    location_values = [
        f"    ({customer_id}, {sql_quote(row['Customer City'])}, {sql_quote(row['Customer State'])}, "
        f"{sql_quote(row['Customer Zipcode'])}, {sql_quote(row['Customer Country'])})"
        for customer_id, row in seen_customers.items()
    ]
    lines.append(",\n".join(location_values) + ";")
    lines.append("")

    for i, row in sample.iterrows():
        customer_id = int(row["Customer Id"])
        hours_ago = rng.randint(1, 24 * 30)
        lines.append(f"WITH o{i} AS (")
        lines.append(
            "    INSERT INTO \"order\" (customer_id, order_city, order_country, order_region, "
            "order_state, market, order_status, placed_at, payment_type)"
        )
        lines.append(
            f"    VALUES ({customer_id}, {sql_quote(row['Order City'])}, "
            f"{sql_quote(row['Order Country'])}, {sql_quote(row['Order Region'])}, "
            f"{sql_quote(row['Order State'])}, {sql_quote(row['Market'])}, "
            f"{sql_quote(row['Order Status'])}, now() - interval '{hours_ago} hours', "
            f"{sql_quote(row['Type'])})"
        )
        lines.append("    RETURNING order_id")
        lines.append(")")
        lines.append(
            f"INSERT INTO shipment (order_id, shipping_mode) SELECT order_id, "
            f"{sql_quote(row['Shipping Mode'])} FROM o{i};"
        )
        lines.append("")

    lines.append("COMMIT;")

    print("\n".join(lines))


if __name__ == "__main__":
    main()
